#!/usr/bin/env python3
"""Embed text files (PTX) as NUL-terminated C char arrays: embed.py out.c name=path ..."""
import sys

out = sys.argv[1]
with open(out, "w") as f:
    f.write("// generated by tools/embed.py — do not edit\n")
    for spec in sys.argv[2:]:
        name, path = spec.split("=", 1)
        data = open(path, "rb").read() + b"\0"
        f.write(f"const char {name}[{len(data)}] = {{\n")
        for i in range(0, len(data), 24):
            f.write(",".join(str(b) for b in data[i:i + 24]) + ",\n")
        f.write("};\n")
